// ---------------------------------------------------------------------------
// A small JSON-Schema (2020-12 subset) checker for the args fragments above:
// type, const, enum, pattern, minLength, maxLength, minimum, required,
// properties, additionalProperties (false or a schema), propertyNames (enum),
// items, minItems, uniqueItems, minProperties, allOf, if/then. Returns error
// strings prefixed with `at`.
// ---------------------------------------------------------------------------
const typeOf = (v) => (v === null ? 'null' : Array.isArray(v) ? 'array' : Number.isInteger(v) ? 'integer' : typeof v);
const typeMatches = (v, t) => t === typeOf(v) || (t === 'number' && typeof v === 'number' && Number.isFinite(v));

export function checkSchema(v, s, at) {
  const errs = [];
  if (s.type !== undefined) {
    const types = Array.isArray(s.type) ? s.type : [s.type];
    if (!types.some((t) => typeMatches(v, t))) return [`${at} must be ${types.join(' or ')}`];
  }
  if ('const' in s && JSON.stringify(v) !== JSON.stringify(s.const)) errs.push(`${at} must be ${JSON.stringify(s.const)}`);
  if (s.enum && !s.enum.some((e) => JSON.stringify(e) === JSON.stringify(v))) errs.push(`${at} must be one of ${s.enum.join('|')}`);
  if (typeof v === 'string') {
    if (s.minLength !== undefined && v.length < s.minLength) errs.push(`${at} must not be empty`);
    if (s.maxLength !== undefined && v.length > s.maxLength) errs.push(`${at} must be at most ${s.maxLength} chars`);
    if (s.pattern && !new RegExp(s.pattern).test(v)) errs.push(`${at} must match ${s.pattern}`);
  }
  if (typeof v === 'number' && s.minimum !== undefined && v < s.minimum) errs.push(`${at} must be >= ${s.minimum}`);
  if (Array.isArray(v)) {
    if (s.minItems !== undefined && v.length < s.minItems) errs.push(`${at} must have at least ${s.minItems} item(s)`);
    if (s.uniqueItems && new Set(v.map((x) => JSON.stringify(x))).size !== v.length) errs.push(`${at} must not repeat an item`);
    if (s.items) v.forEach((x, i) => errs.push(...checkSchema(x, s.items, `${at}[${i}]`)));
  }
  if (isObj(v)) {
    for (const k of s.required ?? []) if (!(k in v)) errs.push(`${at}.${k} is required`);
    if (s.minProperties !== undefined && Object.keys(v).length < s.minProperties) errs.push(`${at} must not be empty`);
    for (const [k, x] of Object.entries(v)) {
      if (s.properties && k in s.properties) errs.push(...checkSchema(x, s.properties[k], `${at}.${k}`));
      else if (s.additionalProperties === false) errs.push(`${at}.${k} is not allowed`);
      else if (isObj(s.additionalProperties)) errs.push(...checkSchema(x, s.additionalProperties, `${at}.${k}`));
      if (s.propertyNames?.enum && !s.propertyNames.enum.includes(k)) errs.push(`${at}.${k} is not allowed here`);
    }
  }
  for (const sub of s.allOf ?? []) {
    if (sub.if) {
      if (checkSchema(v, sub.if, at).length === 0 && sub.then) errs.push(...checkSchema(v, sub.then, at));
    } else errs.push(...checkSchema(v, sub, at));
  }
  return errs;
}

// The JSON-Schema of one op's args: the fragment plus the required keys, closed
// to unknown members. What gen-schema.mjs emits and validateOp checks.
export function argsSchema(name) {
  const d = OPS[name];
  if (!d?.schema) return null;
  return {
    type: 'object',
    ...(d.args.length ? { required: d.args } : {}),
    additionalProperties: false,
    properties: d.schema.properties,
    ...(d.schema.allOf ? { allOf: d.schema.allOf } : {}),
  };
}

// Rules a schema cannot state (D-787). `op` is one operation, `layer` the
// changeset's layer. Returns error strings.
function semanticErrors(o, at, layer) {
  const errs = [];
  const t = o.target ?? {};
  const a = isObj(o.args) ? o.args : {};
  switch (o.op) {
    case 'rename_field':
      if (a.new_name === t.field) errs.push(`${at}.args.new_name must differ from target.field`);
      break;
    case 'change_field_type': {
      const c = isObj(a.conversion) ? a.conversion : {};
      if (typeof a.field_type === 'string' && c.from_type === a.field_type) errs.push(`${at}.args.field_type must differ from args.conversion.from_type`);
      errs.push(...conversionErrors(c.from_type, a.field_type, c, `${at}.args.conversion`));
      break;
    }
    case 'add_choice_value':
    case 'remove_choice_value': {
      if (typeof a.value !== 'string') break;
      const ours = a.value.startsWith(CUSTOMER_CHOICE_PREFIX);
      if (layer === 'customer' && !CUSTOMER_CHOICE_RE.test(a.value)) errs.push(`${at}.args.value: a customer changeset adds and removes only ${CUSTOMER_CHOICE_PREFIX}* values (the reserved customer namespace, D-787)`);
      if (layer !== 'customer' && ours) errs.push(`${at}.args.value: ${CUSTOMER_CHOICE_PREFIX}* is the reserved customer namespace; a ${layer} changeset never uses it (D-787)`);
      if (o.op === 'add_choice_value' && typeof a.after === 'string' && a.after === a.value) errs.push(`${at}.args.after must name another value`);
      break;
    }
    case 'set_view_columns': {
      const names = Array.isArray(a.columns) ? a.columns.map((c) => c?.name) : [];
      if (new Set(names).size !== names.length) errs.push(`${at}.args.columns must not list a field twice`);
      break;
    }
    case 'data_step':
      if (a.kind === 'copy' || a.kind === 'convert') {
        if (a.from && a.from === a.to) errs.push(`${at}.args.to must differ from args.from`);
      }
      if (a.kind === 'convert') errs.push(...conversionErrors(a.from_type, a.to_type, a, `${at}.args`));
      if (a.kind === 'map_values' && isObj(a.map)) {
        const targets = new Set(Object.values(a.map));
        const chained = Object.keys(a.map).filter((k) => targets.has(k) && a.map[k] !== k);
        if ((a.to === undefined || a.to === a.field) && chained.length) errs.push(`${at}.args.map chains values (${chained.join(', ')} is both a source and a target); applying it twice would not be harmless`);
        for (const [k, v] of Object.entries(a.map)) if (k === v) errs.push(`${at}.args.map maps "${k}" to itself`);
      }
      if (a.kind === 'set_default' && a.only_empty === false) errs.push(`${at}.args.only_empty: set_default only fills empty values`);
      break;
    case 'upsert_record':
      if (isObj(t.key)) {
        for (const [k, v] of Object.entries(t.key)) {
          const scalar = typeof v === 'string' || typeof v === 'boolean' || Number.isInteger(v);
          const keyRef = isObj(v) && isObj(v.key) && Object.keys(v).length === 1;
          if (!scalar && !keyRef) errs.push(`${at}.target.key.${k} must be a string, an integer, a boolean, or {"key": {...}} naming a lookup target by its business key (no fractional numbers: a key must checksum identically everywhere)`);
          if (!LOGICAL_RE.test(k)) errs.push(`${at}.target.key.${k} must be a field logical name`);
        }
      }
      // D-787 rule 7 / design §3.9: `changed` (the fields a recorded write
      // set) limits the update of an existing record; each one is set here.
      if ('changed' in a) {
        const set = { ...(isObj(t.key) ? t.key : {}), ...(isObj(a.values) ? a.values : {}) };
        if (!Array.isArray(a.changed) || !a.changed.every((f) => typeof f === 'string' && LOGICAL_RE.test(f))) {
          errs.push(`${at}.args.changed must list field logical names`);
        } else {
          for (const f of a.changed) if (!(f in set)) errs.push(`${at}.args.changed names ${f}, which args.values does not set`);
        }
      }
      break;
    case 'create_entity':
    case 'update_entity': {
      // D-787 rule 7: a declared business key is 1-4 distinct field names
      // (or null to clear it); a reference-data entity needs one.
      const d = isObj(a.definition) ? a.definition : {};
      if ('business_key' in d && d.business_key !== null) {
        const k = d.business_key;
        const ok = Array.isArray(k) && k.length >= 1 && k.length <= 4
          && k.every((f) => typeof f === 'string' && LOGICAL_RE.test(f)) && new Set(k).size === k.length;
        if (!ok) errs.push(`${at}.args.definition.business_key must list 1 to 4 distinct field logical names, or be null`);
      }
      if ('is_reference_data' in d && typeof d.is_reference_data !== 'boolean') errs.push(`${at}.args.definition.is_reference_data must be a boolean`);
      if (d.is_reference_data === true && 'business_key' in d && d.business_key === null) errs.push(`${at}.args.definition: a reference-data entity needs a business key (business_key_missing)`);
      break;
    }
    default:
  }
  return errs;
}

function conversionErrors(from, to, c, at) {
  const errs = [];
  if (typeof from === 'string' && typeof to === 'string' && CONVERSIONS[from] && !CONVERSIONS[from].includes(to)) {
    errs.push(`${at}: no conversion from ${from} to ${to} (defined: ${Object.entries(CONVERSIONS).map(([f, ts]) => `${f}->${ts.join('/')}`).join(', ')})`);
  }
  if ('format' in c && !(from === 'text' && to === 'date') && !(from === 'date' && to === 'text')) errs.push(`${at}.format applies only to text<->date`);
  for (const k of ['true_values', 'false_values']) if (k in c && !(from === 'text' && to === 'bool')) errs.push(`${at}.${k} applies only to text->bool`);
  if ('map' in c && !(from === 'text' && to === 'choice')) errs.push(`${at}.map applies only to text->choice`);
  if (Array.isArray(c.true_values) && Array.isArray(c.false_values)) {
    const t = new Set(c.true_values.map((x) => String(x).trim().toLowerCase()));
    const both = c.false_values.filter((x) => t.has(String(x).trim().toLowerCase()));
    if (both.length) errs.push(`${at}: ${both.join(', ')} is both a true and a false value`);
  }
  return errs;
}

// Cross-operation rules inside one changeset (D-787 rule 1 as amended by
// D-788): after a rename_field, later operations name the field by its new
// name; after a delete_field, no operation names the deleted field except an
// add_field that re-creates the name (names may be reused, there is no name
// history); a field is not created twice.
function crossOpErrors(ops) {
  const errs = [];
  const renamedAway = new Map(); // "entity.old" -> { seq, to }
  const deleted = new Map(); // "entity.field" -> seq of delete_field
  const created = new Map(); // "entity.field" -> seq of add_field
  const fieldRefs = (o) => {
    const t = o.target ?? {};
    const a = isObj(o.args) ? o.args : {};
    const out = [];
    if (typeof t.entity === 'string' && typeof t.field === 'string') out.push(['target.field', t.field]);
    if (o.op === 'data_step') for (const k of ['from', 'to', 'field']) if (typeof a[k] === 'string') out.push([`args.${k}`, a[k]]);
    return out;
  };
  ops.forEach((o, i) => {
    if (!isObj(o)) return;
    const at = `operations[${i}]`;
    const e = o.target?.entity;
    const recreates = o.op === 'add_field' && typeof o.target?.field === 'string';
    for (const [where, f] of fieldRefs(o)) {
      const r = renamedAway.get(`${e}.${f}`);
      if (r && !recreates) {
        errs.push(`${at}.${where} names ${e}.${f}, which operation ${r.seq} renamed to "${r.to}"; later operations use the new name`);
      }
      const d = deleted.get(`${e}.${f}`);
      if (d !== undefined && !recreates) {
        errs.push(`${at}.${where} names ${e}.${f}, which operation ${d} deleted; only an add_field may re-create the name`);
      }
    }
    if (recreates) {
      const n = o.target.field;
      if (created.has(`${e}.${n}`) && !deleted.has(`${e}.${n}`)) errs.push(`${at}: ${e}.${n} is already created by operation ${created.get(`${e}.${n}`)}`);
      created.set(`${e}.${n}`, o.seq);
      deleted.delete(`${e}.${n}`);
      renamedAway.delete(`${e}.${n}`);
    }
    if (o.op === 'rename_field' && typeof o.args?.new_name === 'string') {
      renamedAway.set(`${e}.${o.target?.field}`, { seq: o.seq, to: o.args.new_name });
      renamedAway.delete(`${e}.${o.args.new_name}`);
      deleted.delete(`${e}.${o.args.new_name}`);
    }
    if (o.op === 'delete_field' && typeof o.target?.field === 'string') {
      deleted.set(`${e}.${o.target.field}`, o.seq);
      created.delete(`${e}.${o.target.field}`);
    }
  });
  return errs;
}

// ---------------------------------------------------------------------------
// Canonical JSON: object keys sorted by UTF-16 code unit order (JS default sort,
// identical to byte order for the ASCII keys the format uses), no insignificant
// whitespace, arrays kept in order. Numbers use JSON.stringify's shortest form.
// ---------------------------------------------------------------------------
export function canonicalize(value) {
  if (value === null || typeof value !== 'object') {
    if (typeof value === 'number' && !Number.isFinite(value)) {
      throw new Error('non-finite number cannot be canonicalized');
    }
    if (value === undefined) throw new Error('undefined cannot be canonicalized');
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return `[${value.map(canonicalize).join(',')}]`;
  const keys = Object.keys(value).filter((k) => value[k] !== undefined).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalize(value[k])}`).join(',')}}`;
}

// The checksum covers the whole changeset except the `checksum` member itself.
export function computeChecksum(changeset) {
  const { checksum: _omit, ...rest } = changeset;
  return `sha256:${createHash('sha256').update(canonicalize(rest), 'utf8').digest('hex')}`;
}

// Pretty, stable file text: canonical key order, 2-space indent, trailing newline.
export function toFileText(changeset) {
  return `${JSON.stringify(JSON.parse(canonicalize(changeset)), null, 2)}\n`;
}

export function refOf(cs) {
  return `${cs.layer}/${cs.scope}/${String(cs.seq).padStart(4, '0')}-${cs.name}`;
}

// ---------------------------------------------------------------------------
// Structural validation (schema-lite). Returns a list of error strings.
// ---------------------------------------------------------------------------
const TOP_KEYS = new Set([
  'format', 'id', 'layer', 'scope', 'seq', 'name', 'title', 'description',
  'requires', 'author', 'opened_at', 'closed_at', 'checksum', 'operations', 'summary',
]);
const REQUIRED_TOP = ['format', 'id', 'layer', 'scope', 'seq', 'name', 'title', 'requires', 'author', 'closed_at', 'checksum', 'operations'];

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isStr = (v) => typeof v === 'string' && v.length > 0;

export function validateShape(cs) {
  const errs = [];
  if (!isObj(cs)) return ['changeset must be a JSON object'];
  for (const k of REQUIRED_TOP) if (!(k in cs)) errs.push(`missing required member "${k}"`);
  for (const k of Object.keys(cs)) if (!TOP_KEYS.has(k)) errs.push(`unknown member "${k}"`);
  if ('format' in cs && cs.format !== FORMAT) errs.push(`format must be "${FORMAT}"`);
  if ('id' in cs && !(typeof cs.id === 'string' && UUID_RE.test(cs.id))) errs.push('id must be a lowercase UUIDv7');
  if ('layer' in cs && !LAYERS.includes(cs.layer)) errs.push(`layer must be one of ${LAYERS.join('|')}`);
  if ('scope' in cs && !(typeof cs.scope === 'string' && SCOPE_RE.test(cs.scope))) errs.push('scope must match ' + SCOPE_RE);
  if (cs.layer === 'platform' && cs.scope !== undefined && cs.scope !== 'platform') errs.push('a platform changeset has scope "platform"');
  if ('seq' in cs && !(Number.isInteger(cs.seq) && cs.seq >= 1 && cs.seq <= 9999)) errs.push('seq must be an integer 1..9999');
  if ('name' in cs && !(typeof cs.name === 'string' && NAME_RE.test(cs.name) && cs.name.length <= 60)) errs.push('name must be kebab-case, at most 60 chars');
  if ('title' in cs && !(isStr(cs.title) && cs.title.length <= 200)) errs.push('title must be a non-empty string, at most 200 chars');
  if ('description' in cs && typeof cs.description !== 'string') errs.push('description must be a string');
  if ('author' in cs && !isStr(cs.author)) errs.push('author must be a non-empty string');
  for (const k of ['opened_at', 'closed_at']) {
    if (k in cs && !(typeof cs[k] === 'string' && ISO_RE.test(cs[k]))) errs.push(`${k} must be a UTC ISO-8601 timestamp ending in Z`);
  }
  if ('checksum' in cs && !(typeof cs.checksum === 'string' && CHECKSUM_RE.test(cs.checksum))) errs.push('checksum must be "sha256:<64 hex>"');
  if ('summary' in cs && typeof cs.summary !== 'string') errs.push('summary must be a string');

  if ('requires' in cs) {
    const r = cs.requires;
    if (!isObj(r)) errs.push('requires must be an object');
    else {
      for (const k of Object.keys(r)) if (!['platform', 'after', 'modules'].includes(k)) errs.push(`requires: unknown member "${k}"`);
      if (!('platform' in r)) errs.push('requires.platform is required');
      else if (!(typeof r.platform === 'string' && /^>=\d+\.\d+\.\d+$/.test(r.platform))) errs.push('requires.platform must be ">=MAJOR.MINOR.PATCH"');
      if ('after' in r) {
        if (!Array.isArray(r.after)) errs.push('requires.after must be an array');
        else r.after.forEach((a, i) => { if (!(typeof a === 'string' && REF_RE.test(a))) errs.push(`requires.after[${i}] must be "<layer>/<scope>/<NNNN>-<name>"`); });
      }
      if ('modules' in r) {
        if (!Array.isArray(r.modules) || !r.modules.every((m) => typeof m === 'string' && LOGICAL_RE.test(m))) errs.push('requires.modules must be an array of module keys');
      }
    }
  }

  if ('operations' in cs) {
    if (!Array.isArray(cs.operations) || cs.operations.length === 0) errs.push('operations must be a non-empty array');
    else {
      cs.operations.forEach((op, i) => errs.push(...validateOp(op, i, cs.layer)));
      errs.push(...crossOpErrors(cs.operations));
    }
  }
  return errs;
}

function validateOp(op, i, layer) {
  const at = `operations[${i}]`;
  const errs = [];
  if (!isObj(op)) return [`${at} must be an object`];
  for (const k of Object.keys(op)) if (!['seq', 'op', 'phase', 'target', 'args'].includes(k)) errs.push(`${at}: unknown member "${k}"`);
  if (op.seq !== i + 1) errs.push(`${at}.seq must be ${i + 1} (operations are numbered 1..n in order)`);
  const def = OPS[op.op];
  if (!def) {
    errs.push(`${at}.op "${op.op}" is not in the v1 operation catalogue`);
    return errs;
  }
  if (!PHASES.includes(op.phase)) errs.push(`${at}.phase must be expand|contract`);
  else if (op.phase !== def.phase) errs.push(`${at}.phase for ${op.op} must be "${def.phase}"`);
  if (!isObj(op.target)) errs.push(`${at}.target must be an object`);
  else {
    for (const k of def.target) if (!(k in op.target)) errs.push(`${at}.target.${k} is required for ${op.op}`);
    for (const k of Object.keys(op.target)) if (!def.target.includes(k)) errs.push(`${at}.target.${k} is not a target key of ${op.op}`);
    for (const [k, v] of Object.entries(op.target)) {
      if (k === 'key') { if (!isObj(v) || Object.keys(v).length === 0) errs.push(`${at}.target.key must be a non-empty business-key object`); }
      else if (!isStr(v)) errs.push(`${at}.target.${k} must be a non-empty string`);
    }
    if (typeof op.target.entity === 'string' && !LOGICAL_RE.test(op.target.entity)) errs.push(`${at}.target.entity must be a logical name`);
    if (typeof op.target.field === 'string' && !LOGICAL_RE.test(op.target.field)) errs.push(`${at}.target.field must be a logical name`);
    // Rule 1 of Topic 9: references are logical, never database UUIDs.
    for (const [k, v] of Object.entries(op.target)) {
      if (typeof v === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(v)) errs.push(`${at}.target.${k} is a UUID; changesets reference objects by logical name or business key`);
    }
  }
  if (!('args' in op)) { if (def.args.length) errs.push(`${at}.args is required for ${op.op}`); }
  else if (!isObj(op.args)) errs.push(`${at}.args must be an object`);
  else {
    for (const k of def.args) if (!(k in op.args)) errs.push(`${at}.args.${k} is required for ${op.op}`);
    const schema = argsSchema(op.op);
    if (schema) {
      const missing = new Set(def.args.map((k) => `${at}.args.${k} is required`));
      errs.push(...checkSchema(op.args, schema, `${at}.args`).filter((e) => !missing.has(e)));
    }
  }
  errs.push(...semanticErrors(op, at, layer));
  if (layer === 'customer' && CUSTOMER_FORBIDDEN.has(op.op)) {
    errs.push(`${at}: a customer changeset never creates, retires or restructures entities or fields (decision 0.4/0.5)`);
  }
  if (layer === 'platform' && PLATFORM_FORBIDDEN.has(op.op)) {
    errs.push(`${at}: ${op.op} is not allowed in a platform changeset`);
  }
  return errs;
}

