// Every *.json directly inside `dir` (a changeset folder), sorted by name.
export function listChangesetFiles(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json') && f !== 'manifest.json')
    .sort()
    .map((f) => join(dir, f));
}

// Recursively collect changeset folders under root (folders that directly hold NNNN-*.json).
export function findChangesetFolders(root) {
  const out = [];
  const walk = (d) => {
    const entries = readdirSync(d);
    if (entries.some((e) => FILE_RE.test(e))) out.push(d);
    for (const e of entries) {
      const p = join(d, e);
      if (statSync(p).isDirectory() && e !== 'node_modules' && !e.startsWith('.')) walk(p);
    }
  };
  walk(root);
  return out.sort();
}

export function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

// Validate one folder's numbering: 0001.. contiguous, file name = seq + name.
export function checkFolderOrder(files) {
  const errs = [];
  const seen = new Map();
  files.forEach((file, idx) => {
    const m = FILE_RE.exec(basename(file));
    if (!m) { errs.push(`${basename(file)}: file name must be NNNN-kebab-name.json`); return; }
    const n = Number(m[1]);
    if (seen.has(n)) errs.push(`${basename(file)}: number ${m[1]} is also used by ${seen.get(n)}`);
    seen.set(n, basename(file));
    if (n !== idx + 1) errs.push(`${basename(file)}: expected number ${String(idx + 1).padStart(4, '0')} (numbering is contiguous from 0001)`);
  });
  return errs;
}

// Cross-changeset checks over a set of loaded changesets: file name agrees with
// seq/name, folder agrees with layer/scope (when the path has that shape),
// requires.after points at existing, earlier-ordered changesets, and no cycle.
export function checkGraph(entries) {
  const errs = [];
  const byRef = new Map();
  for (const { file, cs } of entries) byRef.set(refOf(cs), { file, cs });
  for (const { file, cs } of entries) {
    const name = basename(file);
    const m = FILE_RE.exec(name);
    if (m && (Number(m[1]) !== cs.seq || m[2] !== cs.name)) errs.push(`${name}: file name disagrees with seq ${cs.seq} / name "${cs.name}"`);
    // Folder convention: changesets/platform/ and changesets/<layer>/<scope>/. Checked
    // only when the file sits in such a folder (a loose scratch folder is not checked).
    const dirs = dirname(resolve(file)).split(/[\\/]/);
    const parent = dirs[dirs.length - 1];
    const grand = dirs[dirs.length - 2];
    if (parent === 'platform' || LAYERS.includes(grand)) {
      const where = parent === 'platform' ? 'platform/platform' : `${grand}/${parent}`;
      if (where !== `${cs.layer}/${cs.scope}`) errs.push(`${name}: folder ${parent === 'platform' ? 'platform' : where} disagrees with layer/scope ${cs.layer}/${cs.scope}`);
    }
    for (const a of cs.requires?.after ?? []) {
      const dep = byRef.get(a);
      if (!dep) { errs.push(`${name}: requires.after "${a}" not found in the validated set`); continue; }
      if (dep.cs.layer === cs.layer && dep.cs.scope === cs.scope && dep.cs.seq >= cs.seq) {
        errs.push(`${name}: requires.after "${a}" is not earlier in the same folder`);
      }
    }
  }
  // Cycle detection over requires.after plus implicit same-folder predecessor edges.
  const state = new Map();
  const edges = (cs) => {
    const out = [...(cs.requires?.after ?? [])];
    if (cs.seq > 1) {
      const prev = [...byRef.values()].find((e) => e.cs.layer === cs.layer && e.cs.scope === cs.scope && e.cs.seq === cs.seq - 1);
      if (prev) out.push(refOf(prev.cs));
    }
    return out.filter((r) => byRef.has(r));
  };
  const visit = (ref, stack) => {
    if (state.get(ref) === 2) return;
    if (state.get(ref) === 1) { errs.push(`requires.after cycle: ${[...stack, ref].join(' -> ')}`); return; }
    state.set(ref, 1);
    for (const r of edges(byRef.get(ref).cs)) visit(r, [...stack, ref]);
    state.set(ref, 2);
  };
  for (const ref of byRef.keys()) visit(ref, []);
  return errs;
}

// A deterministic apply order: Kahn's algorithm over the same edges, ties broken
// by layer rank (platform < product < project < customer), then scope, then seq.
export function applyOrder(changesets) {
  const rank = (cs) => [LAYERS.indexOf(cs.layer), cs.scope, cs.seq];
  const cmp = (a, b) => {
    const [x, y] = [rank(a), rank(b)];
    for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1;
    return 0;
  };
  const byRef = new Map(changesets.map((cs) => [refOf(cs), cs]));
  const deps = new Map();
  for (const cs of changesets) {
    const d = new Set((cs.requires?.after ?? []).filter((r) => byRef.has(r)));
    const prev = changesets.find((o) => o.layer === cs.layer && o.scope === cs.scope && o.seq === cs.seq - 1);
    if (prev) d.add(refOf(prev));
    deps.set(refOf(cs), d);
  }
  const done = new Set();
  const out = [];
  while (out.length < changesets.length) {
    const ready = changesets.filter((cs) => !done.has(refOf(cs)) && [...deps.get(refOf(cs))].every((r) => done.has(r))).sort(cmp);
    if (!ready.length) throw new Error('requires.after cycle; no apply order exists');
    done.add(refOf(ready[0]));
    out.push(ready[0]);
  }
  return out;
}
