#!/usr/bin/env node
// AK5-T1: turn an extracted clean-exit archive (Y5-T5) into SQL for plain
// PostgreSQL, with no Attome running. Run it on the extracted folder:
//
//   node scripts/exit/load-postgres.mjs <archive-folder> [--schema attome_exit] [--foreign-keys]
//
// It writes `schema.sql` (one table per `data/<entity>.csv`, typed from
// `metadata/bundle.json`, plus the audit tables) and `load.sql` (psql
// `\copy` commands) into the folder. Then, from the folder:
//
//   psql "<connection>" -v ON_ERROR_STOP=1 -f schema.sql -f load.sql
//
// Works on Windows, macOS and Linux (Node 18 or later, no packages).

import { existsSync, readdirSync, readFileSync, writeFileSync, openSync, readSync, closeSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The type of each system column every entity table has. */
export const SYSTEM_COLUMNS = {
  id: 'uuid',
  created_at: 'timestamptz',
  created_by: 'uuid',
  modified_at: 'timestamptz',
  modified_by: 'uuid',
  organization_ref: 'uuid',
  is_active: 'boolean',
  row_version: 'bigint',
  owner_ref: 'uuid',
  owner_type: 'integer',
};

/** The PostgreSQL type of a bundle attribute (its `field_type` and options). */
export function columnType(attribute) {
  const multi = attribute?.options?.multi === true;
  switch (attribute?.field_type) {
    case 'number':
    case 'currency':
    case 'rollup':
      return 'numeric';
    case 'date':
      return 'date';
    case 'date_time':
      return 'timestamptz';
    case 'time':
      return 'time';
    case 'geolocation':
    case 'json':
      return 'jsonb';
    case 'bool':
      return 'boolean';
    case 'choice':
      return multi ? 'text[]' : 'text';
    case 'lookup':
      return 'uuid';
    case 'file':
    case 'image':
      return multi ? 'jsonb' : 'text';
    default:
      return 'text';
  }
}

/** `name` as a quoted SQL identifier. */
export function ident(name) {
  return `"${String(name).replaceAll('"', '""')}"`;
}

/** `text` as a quoted SQL literal. */
export function literal(text) {
  return `'${String(text).replaceAll("'", "''")}'`;
}

/** The column names of a CSV header line (names never hold commas). */
export function headerColumns(line) {
  return line
    .replace(/\r?\n$/, '')
    .split(',')
    .map((c) => c.trim().replace(/^"(.*)"$/, '$1').replaceAll('""', '"'))
    .filter((c) => c.length > 0);
}

function firstLine(path) {
  const fd = openSync(path, 'r');
  try {
    const buf = Buffer.alloc(64 * 1024);
    const n = readSync(fd, buf, 0, buf.length, 0);
    const text = buf.subarray(0, n).toString('utf8').replace(/^﻿/, '');
    const end = text.indexOf('\n');
    return end < 0 ? text : text.slice(0, end);
  } finally {
    closeSync(fd);
  }
}

/**
 * The SQL for one archive: `{ schema, load }`. `entities` is the bundle's
 * `entities`; `tables` maps each table name to its CSV path (relative to
 * the folder) and header columns. Pure.
 */
export function buildSql(entities, tables, { schemaName = 'attome_exit', foreignKeys = false } = {}) {
  const byName = new Map(entities.map((e) => [e.logicalname, e]));
  const schema = [
    '-- Generated by scripts/exit/load-postgres.mjs from an Attome exit archive.',
    `CREATE SCHEMA IF NOT EXISTS ${ident(schemaName)};`,
    `SET search_path = ${ident(schemaName)};`,
    '',
  ];
  const load = [`SET search_path = ${ident(schemaName)};`];
  const fks = [];
  for (const [table, { file, columns }] of [...tables].sort(([a], [b]) => a.localeCompare(b))) {
    const entity = byName.get(table);
    const attributes = new Map((entity?.attributes ?? []).map((a) => [a.logicalname, a]));
    const defs = columns.map((column) => {
      const type = entity
        ? SYSTEM_COLUMNS[column] ?? columnType(attributes.get(column))
        : 'text';
      return `  ${ident(column)} ${type}`;
    });
    if (entity && columns.includes('id')) defs.push('  PRIMARY KEY ("id")');
    schema.push(`CREATE TABLE IF NOT EXISTS ${ident(table)} (\n${defs.join(',\n')}\n);`);
    if (entity?.display_name) {
      schema.push(`COMMENT ON TABLE ${ident(table)} IS ${literal(entity.display_name)};`);
    }
    for (const column of columns) {
      const a = attributes.get(column);
      if (a?.display_name) {
        schema.push(`COMMENT ON COLUMN ${ident(table)}.${ident(column)} IS ${literal(a.display_name)};`);
      }
      if (foreignKeys && a?.field_type === 'lookup' && a.lookup_entity && tables.has(a.lookup_entity)) {
        fks.push(
          `ALTER TABLE ${ident(table)} ADD FOREIGN KEY (${ident(column)}) ` +
            `REFERENCES ${ident(a.lookup_entity)} ("id") NOT VALID;`,
        );
      }
    }
    schema.push('');
    const cols = columns.map(ident).join(', ');
    load.push(`\\copy ${ident(table)} (${cols}) FROM ${literal(file)} WITH (FORMAT csv, HEADER true)`);
  }
  // Foreign keys come after every table exists; NOT VALID so rows that
  // point at deleted records still load.
  return { schema: [...schema, ...fks, ''].join('\n'), load: [...load, ''].join('\n') };
}

/** Reads an extracted archive folder: the bundle's entities and the tables. */
export function readArchive(folder) {
  const bundlePath = join(folder, 'metadata', 'bundle.json');
  if (!existsSync(bundlePath)) throw new Error(`${bundlePath} not found: is this an extracted exit archive?`);
  const bundle = JSON.parse(readFileSync(bundlePath, 'utf8'));
  const tables = new Map();
  for (const dir of ['data', 'audit']) {
    const path = join(folder, dir);
    if (!existsSync(path)) continue;
    for (const name of readdirSync(path).filter((n) => n.endsWith('.csv'))) {
      const file = `${dir}/${name}`;
      tables.set(name.slice(0, -4), { file, columns: headerColumns(firstLine(join(folder, file))) });
    }
  }
  return { entities: bundle.entities ?? [], tables };
}

function main(argv) {
  const args = argv.slice(2);
  const folder = args.find((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--schema');
  if (!folder) {
    console.error('usage: node scripts/exit/load-postgres.mjs <archive-folder> [--schema <name>] [--foreign-keys]');
    process.exit(2);
  }
  const schemaAt = args.indexOf('--schema');
  const schemaName = schemaAt >= 0 ? args[schemaAt + 1] : 'attome_exit';
  const { entities, tables } = readArchive(folder);
  const sql = buildSql(entities, tables, { schemaName, foreignKeys: args.includes('--foreign-keys') });
  writeFileSync(join(folder, 'schema.sql'), sql.schema);
  writeFileSync(join(folder, 'load.sql'), sql.load);
  console.log(`${tables.size} tables: wrote schema.sql and load.sql in ${folder}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv);
}
