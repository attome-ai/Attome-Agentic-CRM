# Z11-T13: builds attome-rules-wasm to WebAssembly and writes the module that
# @attome/base's RulesEvaluatorService loads into
# web/projects/base/src/lib/rules/wasm. The generated glue (.ts) and .wasm
# are committed, so an npm build needs no Rust; run this again after a change to
# attome-rules or attome-rules-wasm, and commit what it writes.
#
#   pwsh scripts/build-rules-wasm.ps1
#
# Needs the wasm32-unknown-unknown target and wasm-bindgen-cli at the
# wasm-bindgen version Cargo.lock pins (0.2.129):
#   rustup target add wasm32-unknown-unknown
#   cargo install wasm-bindgen-cli --version 0.2.129 --locked

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

rustup target add wasm32-unknown-unknown
if ($LASTEXITCODE -ne 0) { throw 'rustup target add failed' }

cargo build -p attome-rules-wasm --release --target wasm32-unknown-unknown
if ($LASTEXITCODE -ne 0) { throw 'cargo build failed' }

$out = Join-Path $root 'web/projects/base/src/lib/rules/wasm'
wasm-bindgen --target web --out-dir $out `
    (Join-Path $root 'target/wasm32-unknown-unknown/release/attome_rules_wasm.wasm')
if ($LASTEXITCODE -ne 0) { throw 'wasm-bindgen failed' }

# ng-packagr compiles TypeScript only, so the generated glue is kept as an
# unchecked .ts module (its .d.ts files would then shadow it).
$glue = Join-Path $out 'attome_rules_wasm.js'
$header = "// @ts-nocheck`n// Generated by wasm-bindgen (scripts/build-rules-wasm.ps1); do not edit.`n"
Set-Content -Path (Join-Path $out 'attome_rules_wasm.ts') -Value ($header + (Get-Content -Raw $glue)) -Encoding utf8 -NoNewline
Remove-Item $glue, (Join-Path $out 'attome_rules_wasm.d.ts'), (Join-Path $out 'attome_rules_wasm_bg.wasm.d.ts')

Get-ChildItem $out | Format-Table Name, Length
