# Z13-T9: builds attome-html-wasm to WebAssembly and writes the module that
# @attome/base's TemplateRendererService loads into
# web/projects/base/src/lib/rules/html-wasm. The generated glue (.ts) and .wasm
# are committed, so an npm build needs no Rust; run this again after a change to
# attome-html, attome-rules or attome-html-wasm, and commit what it writes.
#
#   pwsh scripts/build-html-wasm.ps1
#
# Needs what scripts/build-rules-wasm.ps1 needs: the wasm32-unknown-unknown
# target and wasm-bindgen-cli at the version Cargo.lock pins.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

rustup target add wasm32-unknown-unknown
if ($LASTEXITCODE -ne 0) { throw 'rustup target add failed' }

cargo build -p attome-html-wasm --release --target wasm32-unknown-unknown
if ($LASTEXITCODE -ne 0) { throw 'cargo build failed' }

$out = Join-Path $root 'web/projects/base/src/lib/rules/html-wasm'
wasm-bindgen --target web --out-dir $out `
    (Join-Path $root 'target/wasm32-unknown-unknown/release/attome_html_wasm.wasm')
if ($LASTEXITCODE -ne 0) { throw 'wasm-bindgen failed' }

# As in build-rules-wasm.ps1: ng-packagr compiles TypeScript only.
$glue = Join-Path $out 'attome_html_wasm.js'
$header = "// @ts-nocheck`n// Generated by wasm-bindgen (scripts/build-html-wasm.ps1); do not edit.`n"
Set-Content -Path (Join-Path $out 'attome_html_wasm.ts') -Value ($header + (Get-Content -Raw $glue)) -Encoding utf8 -NoNewline
Remove-Item $glue, (Join-Path $out 'attome_html_wasm.d.ts'), (Join-Path $out 'attome_html_wasm_bg.wasm.d.ts')

Get-ChildItem $out | Format-Table Name, Length
